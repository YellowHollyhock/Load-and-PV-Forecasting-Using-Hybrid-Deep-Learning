df = pd.merge(weather_df, load_df, on="Timestamp", how="inner").sort_values("Timestamp").reset_index(drop=True)
df = df.dropna(subset=[TARGET_PV, TARGET_LOAD])

# Define features including time features
BASE_FEATURES = ['Temperature', 'Dew.Point', 'Relative.Humidity', 'Pressure', 'Wind.Speed',
                 'Wind.Direction', 'Cloud.Type', 'Solar.Zenith.Angle', 'Precipitable.Water',
                 'DNI', 'DHI']

# Add time features
df['hour'] = df['Timestamp'].dt.hour
df['dayofweek'] = df['Timestamp'].dt.dayofweek
df['month'] = df['Timestamp'].dt.month
df['hour_sin']  = np.sin(2*np.pi*df['hour']/24)
df['hour_cos']  = np.cos(2*np.pi*df['hour']/24)
df['dow_sin']   = np.sin(2*np.pi*df['dayofweek']/7)
df['dow_cos']   = np.cos(2*np.pi*df['dayofweek']/7)
df['mon_sin']   = np.sin(2*np.pi*df['month']/12)
df['mon_cos']   = np.cos(2*np.pi*df['month']/12)
TIME_FEATS = ['hour_sin','hour_cos','dow_sin','dow_cos','mon_sin','mon_cos']
FEATURES = BASE_FEATURES + TIME_FEATS


# -------------------------
# Helpers
# -------------------------
def create_sequences(X, y, timesteps):
    Xs, ys = [], []
    for i in range(len(X) - timesteps):
        Xs.append(X[i:i+timesteps])
        ys.append(y[i+timesteps])
    return np.array(Xs), np.array(ys)

def safe_mape(y_true, y_pred):
    mask = y_true > THRESHOLD_DAY
    if mask.sum() == 0: return np.nan
    return np.mean(np.abs((y_true[mask]-y_pred[mask])/y_true[mask]))*100

def smape(y_true, y_pred):
    return 100*np.mean(2*np.abs(y_pred-y_true)/(np.abs(y_true)+np.abs(y_pred)+1e-8))

def evaluate(y_true, y_pred, label=""):
    mae = mean_absolute_error(y_true, y_pred)
    rmse = sqrt(mean_squared_error(y_true, y_pred))
    r2 = r2_score(y_true, y_pred)
    y_range = np.max(y_true)-np.min(y_true)
    nmae = mae/y_range
    nrmse = rmse/y_range
    acc = (1-nmae)*100
    mape = safe_mape(y_true,y_pred)
    smape_val = smape(y_true,y_pred)
    print(f"\n--- {label} ---")
    print(f"MAE={mae:.3f}, RMSE={rmse:.3f}, R²={r2:.4f}, NMAE={nmae:.4f}, NRMSE={nrmse:.4f}, Acc={acc:.2f}%")
    print(f"MAPE={mape:.2f}%, SMAPE={smape_val:.2f}%")
    return [mae,rmse,r2,nmae,nrmse,acc,mape,smape_val]

def build_lstm_feature_model(input_shape):
    inp = Input(shape=input_shape)
    x = LSTM(64, return_sequences=True)(inp)
    x = Dropout(0.2)(x)
    x = LSTM(64, return_sequences=False)(x)
    x = Dropout(0.2)(x)
    x = Dense(64, activation="relu")(x)
    feat = Dense(32, activation="relu", name="feature_vector")(x)
    out = Dense(1, activation="linear")(feat)
    return Model(inputs=inp, outputs=out)


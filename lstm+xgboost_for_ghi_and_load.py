EPOCHS      = 100
PATIENCE    = 15
THRESHOLD_DAY = 0.1
TARGET_PV   = "GHI"
TARGET_LOAD = "B4"

PANEL_AREA_M2    = 1.0
PANEL_EFFICIENCY = 0.20

# -------------------------
# Load & preprocess
# -------------------------
